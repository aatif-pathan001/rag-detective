"""
Data models and schemas for RAG Detective.
Uses Pydantic v2 for data validation, serialization, and OpenAPI compatibility.
"""

from __future__ import annotations

from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field


class DocumentChunk(BaseModel):
    """
    Standard representation of an indexed text chunk in RAG Detective.
    """
    id: str = Field(..., description="Unique chunk identifier, e.g. 'Chunk_1'")
    page_content: str = Field(..., description="Extracted textual content of the chunk")
    metadata: Dict[str, Any] = Field(default_factory=dict, description="Metadata key-value pairs (headers, source, etc.)")

    def to_langchain(self) -> Any:
        """Converts chunk to a LangChain Document object."""
        from langchain_core.documents import Document
        return Document(
            id=self.id,
            page_content=self.page_content,
            metadata=self.metadata,
        )

    @classmethod
    def from_langchain(cls, doc: Any, fallback_id: Optional[str] = None) -> DocumentChunk:
        """Creates a DocumentChunk from a LangChain Document."""
        doc_id = getattr(doc, "id", None) or fallback_id or ""
        return cls(
            id=doc_id,
            page_content=doc.page_content,
            metadata=doc.metadata or {},
        )


class SubQuery(BaseModel):
    """
    Dual-representation query generated by Query Rewriter.
    Contains both semantic dense query and sparse keyword search query.
    """
    dense: str = Field(..., description="Self-contained natural-language query for semantic/dense search")
    sparse: str = Field(..., description="Space-separated keywords and quoted phrases for BM25/sparse search")


class QueryRewriteResult(BaseModel):
    """
    Structured output from Query Rewriter LLM.
    """
    needs_retrieval: bool = Field(
        default=True,
        description="Whether this user message requires document retrieval"
    )
    needs_clarification: bool = Field(
        default=False,
        description="Whether this query is too ambiguous to rewrite without guessing"
    )
    clarifying_question: Optional[str] = Field(
        default=None,
        description="Clarifying question to prompt the user with if ambiguous"
    )
    sub_queries: List[SubQuery] = Field(
        default_factory=list,
        description="Decomposed sub-queries with dense and sparse components"
    )


class SearchResult(BaseModel):
    """
    Individual document match returned by any retrieval engine (dense, sparse, or hybrid fusion).
    """
    chunk_id: str = Field(..., description="Unique ID of the matched chunk")
    content: str = Field(..., description="Text content of the retrieved chunk")
    metadata: Dict[str, Any] = Field(default_factory=dict, description="Chunk metadata")
    score: float = Field(..., description="Relevance score (cosine similarity, BM25 score, or RRF score)")
    rank: int = Field(..., description="Rank in the result list (1-indexed)")
    engine: str = Field(..., description="Source engine: 'dense', 'sparse', or 'hybrid_rrf'")


class InvestigationRequest(BaseModel):
    """
    Input request to the RAG Detective pipeline.
    """
    user_query: str = Field(..., min_length=1, max_length=2000, description="User's question or investigation lead")
    chat_history: Optional[str] = Field(None, max_length=10000, description="Prior conversation turns for context resolution")
    document_context: Optional[str] = Field(None, max_length=4000, description="Optional description of the active document collection")
    top_k: int = Field(3, ge=1, le=50, description="Number of top context chunks to supply to the synthesizer")
    alpha: float = Field(0.3, ge=0.0, le=1.0, description="Weight given to sparse retrieval in Weighted RRF")
    k: int = Field(60, ge=1, le=1000, description="RRF smoothing constant")


class InvestigationResult(BaseModel):
    """
    Complete investigation response produced by RAG Detective backend.
    """
    query: str = Field(..., description="Original user query")
    needs_retrieval: bool = Field(..., description="Whether retrieval was performed")
    needs_clarification: bool = Field(..., description="Whether clarification is requested")
    clarifying_question: Optional[str] = Field(None, description="Clarification question if needed")
    sub_queries: List[SubQuery] = Field(default_factory=list, description="Sub-queries derived by rewriter")
    answer: str = Field(..., description="Synthesized detective answer strictly grounded in retrieved evidence")
    evidence: List[SearchResult] = Field(default_factory=list, description="Top ranked context chunks used for synthesis")
    retrieved_chunk_ids: List[str] = Field(default_factory=list, description="List of IDs for all chunks considered")
    metadata: Dict[str, Any] = Field(default_factory=dict, description="Execution metrics and metadata")


class IngestionResponse(BaseModel):
    """
    Result returned upon document ingestion.
    """
    source: str = Field(..., description="Filename or source path")
    total_chunks: int = Field(..., description="Number of chunks created and indexed")
    chunk_ids: List[str] = Field(default_factory=list, description="Generated chunk identifiers")
    metadata: Dict[str, Any] = Field(default_factory=dict, description="Ingestion metadata")
